#!/usr/bin/env python3
"""Validate the corpus and generate the human-readable CALLS.md index.

CI gate: `python3 tools/build_calls.py --check`

The check is the important part. It enforces the invariant that makes this
project worth more than a cookbook:

    an entry that claims to be verified MUST carry execution evidence,
    and two entries MUST NOT describe the same call.

A forged entry -- one that types `verified_by: recorded` with no evidence
-- fails the gate. That is the whole point of the gate.
"""
from __future__ import annotations

import argparse
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "tools"))

import call_core as core  # noqa: E402

CORPUS = os.path.join(REPO, "data", "calls.yaml")
INDEX = os.path.join(REPO, "CALLS.md")


def index_path_for(corpus_path: str) -> str:
    """Where the index for a given corpus belongs.

    The index is a view of the corpus, so it must live next to the corpus
    it describes. The default corpus indexes to the repo's CALLS.md; any
    other corpus (a harness output, a test fixture, an alternate corpus
    via CALL_ANYTHING_CORPUS) indexes to a CALLS.md beside itself.

    Writing an alternate corpus's entries into the repo's CALLS.md would
    pollute the real index and break the CI gate for the real corpus.
    """
    if os.path.abspath(corpus_path) == os.path.abspath(CORPUS):
        return INDEX
    return os.path.join(os.path.dirname(os.path.abspath(corpus_path)),
                        "CALLS.md")


def regenerate_index(corpus_path: str) -> str:
    """Rewrite the index for `corpus_path` and return the path written.

    The corpus and the generated index are two views of the same data.
    Writing the corpus without regenerating the index leaves them
    inconsistent, and `tools/build_calls.py --check` (the CI gate) then
    fails with "index is stale" -- a self-inflicted red build caused by
    using the tooling as designed.

    Never raises: the corpus write has already succeeded by the time this
    is called, so a failure here must not lose the call.
    """
    entries = core.load_corpus(corpus_path)
    content = render(entries)
    index = index_path_for(corpus_path)
    with open(index, "w", encoding="utf-8") as fh:
        fh.write(content)
    return index


def render(entries: list[core.CallEntry]) -> str:
    verified = [e for e in entries if e.is_verified]
    claimed = [e for e in entries if not e.is_verified]

    lines = []
    lines.append("# Call-Anything index")
    lines.append("")
    lines.append(
        "Generated by `tools/build_calls.py`. Do not edit by hand -- "
        "edit `data/calls.yaml` and regenerate."
    )
    lines.append("")
    lines.append(
        f"**{len(verified)} verified calls** across "
        f"**{len({e.server for e in entries})} servers**, "
        f"covering **{len({(e.server, e.tool) for e in entries})} tools**. "
        f"**{len(claimed)}** unverified claim(s) excluded from this index."
    )
    lines.append("")

    by_server: dict[str, list[core.CallEntry]] = {}
    for e in verified:
        by_server.setdefault(e.server, []).append(e)

    for server in sorted(by_server):
        lines.append(f"## {server}")
        lines.append("")
        lines.append("| tool | arguments | what it does | evidence | verified |")
        lines.append("|---|---|---|---|---|")
        for e in sorted(by_server[server], key=lambda x: x.tool):
            args = ", ".join(
                f"`{k}={json_escape(v)}`" for k, v in sorted(e.arguments.items())
            ) or "_(none)_"
            ev = e.evidence.replace("|", "\\|").replace("\n", " ")[:80]
            lines.append(
                f"| `{e.tool}` | {args} | {e.summary} | {ev}… | "
                f"{e.verified_at} ({e.verified_by}) |"
            )
        lines.append("")

    if claimed:
        lines.append("## Unverified claims")
        lines.append("")
        lines.append(
            "These are asserted but carry no execution evidence. They are "
            "excluded from the index above and from `find_call` by default."
        )
        lines.append("")
        for e in claimed:
            lines.append(f"- `{e.id}` — {e.summary}")
        lines.append("")

    return "\n".join(lines) + "\n"


def json_escape(v) -> str:
    import json
    s = json.dumps(v, sort_keys=True)
    return s if len(s) < 40 else s[:37] + "..."


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="fail if the index is stale or the corpus is invalid")
    ap.add_argument("--corpus", default=CORPUS)
    ap.add_argument("--index", default=INDEX)
    ap.add_argument("--no-index-check", action="store_true",
                    help="skip the CALLS.md staleness check (for corpora "
                         "generated by the harness)")
    args = ap.parse_args()

    ok, errors = core.validate_corpus(args.corpus)
    if not ok:
        print("CORPUS INVALID:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        return 1
    print(f"corpus OK: {len(core.load_corpus(args.corpus))} entries")

    entries = core.load_corpus(args.corpus)
    content = render(entries)

    if args.check:
        if args.no_index_check:
            print("index check skipped")
            return 0
        if not os.path.exists(args.index):
            print(f"index missing: {args.index}", file=sys.stderr)
            return 1
        with open(args.index, "r", encoding="utf-8") as fh:
            current = fh.read()
        if current != content:
            print(
                "index is stale: run `python3 tools/build_calls.py`",
                file=sys.stderr,
            )
            return 1
        print(f"index up to date: {args.index}")
        return 0

    with open(args.index, "w", encoding="utf-8") as fh:
        fh.write(content)
    print(f"wrote {args.index}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
